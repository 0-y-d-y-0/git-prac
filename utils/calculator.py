def add_nums(a,b):
    """This function adds two numbers   """
    return a + b

def div_nums(a,b):
    """This function divides two numbers   """  
    return a / b

def sub_nums(a,b):
    """This function subtracts two numbers   """
    return a - b

def pow_nums(a,b):
    """This function raises a to the power of b   """
    return a ** b

def mul_nums(a,b):
    """This function multiplies two numbers   """       
    return a * b

